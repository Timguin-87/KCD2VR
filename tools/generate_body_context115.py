"""Prove one layer-specific idle exception from the supplied retail ADBs.

An alias shared by a hand-holding layer and a mounted overlay is not evidence
that the mounted action is playing. Unknown aliases/layouts still fail closed.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ALIAS = 'holditem_idle_sword_rhand'
DEFS = 'Mannequin/ADB/kcd_male_controllerdefs.xml'


def derive(archive):
    uses = []
    with zipfile.ZipFile(archive) as z:
        defs = ET.fromstring(z.read(DEFS))
        scopes = defs.find('ScopeDefs')
        hold = defs.find('FragmentDefs/HoldItemRight')
        assert all(d.get('scopes') == 'HoldItemRight' for d in [hold, *hold])
        assert int(scopes.find('HoldItemRight').get('layer')) == 4
        assert int(scopes.find('UpperBody').get('layer')) == 6
        ordinary = False
        for path in sorted(z.namelist()):
            if not path.endswith('.adb') or not path.rsplit('/', 1)[-1].startswith('kcd_male'):
                continue
            data = z.read(path)
            for entry in ET.fromstring(data).findall('./FragmentList/*'):
                for frag in entry:
                    for index, layer in enumerate(frag.findall('AnimLayer')):
                        if not any(a.get('name') == ALIAS for a in layer.findall('Animation')):
                            continue
                        if entry.tag == 'HoldItemRight' and index == 0:
                            ordinary = True
                        protected = any(x in entry.tag.lower() for x in
                            ('hit', 'clinch', 'sync', 'mercy', 'death', 'stealth', 'horse')) or 'horse' in str(frag.attrib).lower()
                        if not protected:
                            continue
                        # All protected uses of this alias must be secondary
                        # HolsterWeapon overlays at layer 7, never layer 4.
                        assert entry.tag == 'HolsterWeapon' and index == 1
                        tags = set(frag.get('Tags', '').split('+'))
                        definition = defs.find('FragmentDefs/HolsterWeapon')
                        candidates = [definition] + [o for o in definition
                            if set(filter(None, o.get('tags', '').split('+'))) <= tags and not o.get('fragTags')]
                        assert all(d.get('scopes', '').split('+')[0] == 'UpperBody' for d in candidates)
                        uses.append(dict(path=path, sha256=hashlib.sha256(data).hexdigest(),
                            fragment=entry.tag, guid=frag.get('GUID'), tags=frag.get('Tags'),
                            anim_layer_index=index, native_layer=7))
        assert ordinary and uses
        return dict(alias=ALIAS, exception_layer=4, protected_uses=uses,
                    controllerdefs_sha256=hashlib.sha256(z.read(DEFS)).hexdigest())


def main():
    p = argparse.ArgumentParser(); p.add_argument('archive'); p.add_argument('--check', action='store_true'); a = p.parse_args()
    evidence = derive(a.archive)
    outputs = {
        ROOT/'src/vrik/body_context115.h': '// Generated by tools/generate_body_context115.py.\n#pragma once\n'
        '#include <cstring>\nnamespace kcd2vr::vr_combat111 {\n'
        'inline bool SharedHoldingIdle115(const char* name,int layer) noexcept {\n'
        '    return layer==4&&name&&std::strcmp(name,"holditem_idle_sword_rhand")==0;\n}\n}\n',
        ROOT/'tests/fixtures/body_context115.json': json.dumps(evidence, indent=2)+'\n'}
    for path, content in outputs.items():
        if a.check:
            assert path.read_text() == content, path
        else:
            path.write_text(content)
    print(f'PASS: {len(evidence["protected_uses"])} protected uses remain layer 7; ordinary holding layer 4 qualified')


if __name__ == '__main__':
    main()
