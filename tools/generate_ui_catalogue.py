#!/usr/bin/env python3
"""Offline-only generator. Production reads constexpr data; it never parses XML/JSON.
--check fails if the committed header drifted. No network or third-party packages.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROLES = ('Hud', 'FullMenu', 'PadMenu', 'ApseRoot', 'ApseChild', 'CraftRoot',
         'Modal', 'ContextMenu', 'NativeContext', 'WorldTexture', 'FieldEffect', 'PassiveOverlay', 'PassiveBlocking')

def render(data: dict) -> str:
    elements = data['elements']
    if len(elements) != 28 or len({e['element'].casefold() for e in elements}) != 28:
        raise ValueError('Expected exactly the 28 distinct supplied native UIElements')
    align = {'fullscreen':'FullScreen', 'fixdyntexsize':'FixedTexture', 'dynamic':'CenteredDynamic'}
    lines = ['#pragma once', '// Generated by tools/generate_ui_catalogue.py. Edit data/native_ui_catalogue.json.',
        '// Native dimensions are logical stage / texture constraints, NEVER metres or VR scale.',
        '#include "ui_native_state.h"', '#include <array>', '#include <string_view>', '#include <cstdint>',
        'namespace kcd2vr::ui_native_catalogue {',
        'enum class Alignment { FullScreen, FixedTexture, CenteredDynamic };',
        'enum class Role { '+', '.join(ROLES)+' };',
        'struct Entry {',
        '    const char* name; ui_native_state::Kind kind; Role role; Alignment alignment;',
        '    unsigned stage_width, stage_height, texture_width, texture_height; int layer;',
        '    int mouse, cursor, controller; // -1 = unspecified in native XML, NOT false',
        '};',
        f'inline constexpr std::array<Entry, {len(elements)}> Entries{{{{']
    for e in elements:
        if e['role'] not in ROLES: raise ValueError(f"Unknown role: {e['role']}")
        stage=e['logical_stage']; pos=e['position_constraints']; attrs=e['native_attributes']
        if stage['width'] <= 0 or stage['height'] <= 0: raise ValueError('Invalid logical stage')
        fields=[json.dumps(e['element']), 'ui_native_state::'+e['kind'], 'Role::'+e['role'],
            'Alignment::'+align[e['align']['mode']], str(int(stage['width'])), str(int(stage['height'])),
            str(int(pos.get('width',0))),str(int(pos.get('height',0))),str(int(e['gfx']['layer'])),
            *(str(int(attrs.get(a,-1))) for a in ('mouseevents','cursor','controller_input'))]
        lines.append('    {'+', '.join(fields)+'},')
    lines += ['}};',
        'constexpr char Lower(char c) noexcept { return c >= \'A\' && c <= \'Z\' ? char(c+(\'a\'-\'A\')) : c; }',
        'constexpr bool Equal(std::string_view a, std::string_view b) noexcept {',
        '    if(a.size()!=b.size()) return false;',
        '    for(std::size_t i=0;i<a.size();++i) if(Lower(a[i])!=Lower(b[i])) return false;',
        '    return true;', '}',
        'constexpr const Entry* Find(std::string_view name) noexcept {',
        '    for(const auto& e:Entries) if(Equal(e.name,name)) return &e;',
        '    return nullptr;', '}',
        'constexpr const Entry* Find(ui_native_state::Kind kind) noexcept {',
        '    for(const auto& e:Entries) if(e.kind==kind) return &e;',
        '    return nullptr;', '}',
        'constexpr std::uint32_t Mask(Role role) noexcept {',
        '    std::uint32_t mask=0;',
        '    for(const auto& e:Entries) if(e.role==role) mask|=ui_native_state::Bit(e.kind);',
        '    return mask;', '}',
        'constexpr const char* Name(ui_native_state::Kind kind) noexcept {',
        '    if(const auto* e=Find(kind)) return e->name;',
        '    return kind==ui_native_state::Shop?"ShopLifecycle":kind==ui_native_state::Crafting?"CraftingLifecycle":"Unknown";',
        '}',
        'inline constexpr auto ApseMask = Mask(Role::ApseRoot);',
        'inline constexpr auto ContextMask = Mask(Role::ContextMenu);',
        'inline constexpr auto NativeContextMask = Mask(Role::NativeContext);',
        'inline constexpr auto PassiveMask = Mask(Role::PassiveBlocking);',
        'inline constexpr auto ModalMask = Mask(Role::Modal);',
        'inline constexpr auto MenuMask = Mask(Role::FullMenu)|Mask(Role::PadMenu);',
        'inline constexpr auto CraftMask = Mask(Role::CraftRoot);',
        '// Only these kinds can alter presentation/input focus. HUD/effects/world textures,',
        '// child textures and the broad crafting lifecycle are intentionally not focus owners.',
        'inline constexpr std::uint32_t OwnershipMask = ApseMask|ContextMask|NativeContextMask|PassiveMask|ModalMask|MenuMask|CraftMask|ui_native_state::Bit(ui_native_state::Shop);',
        'inline constexpr unsigned HudStageWidth = Find(ui_native_state::Hud)->stage_width;',
        'inline constexpr unsigned HudStageHeight = Find(ui_native_state::Hud)->stage_height;',
        'static_assert(Entries.size()+2 == ui_native_state::Count);',
        'static_assert(Find(ui_native_state::AlchemyBook)->stage_width == 2048);',
        'static_assert(Find(ui_native_state::AlchemyBook)->texture_width == 256);',
        '} // namespace kcd2vr::ui_native_catalogue', '']
    return '\n'.join(lines)

def main() -> int:
    p=argparse.ArgumentParser(description=__doc__); p.add_argument('--check',action='store_true'); args=p.parse_args()
    data=json.loads((ROOT/'data/native_ui_catalogue.json').read_text(encoding='utf-8'))
    output=ROOT/'src/ui_native_catalogue.h'; text=render(data)
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != text:
            print('FAIL: generated UI catalogue differs; run tools/generate_ui_catalogue.py'); return 1
        print('PASS: 28 native definitions match the committed constexpr catalogue'); return 0
    output.write_text(text,encoding='utf-8'); print(output); return 0
if __name__ == '__main__': raise SystemExit(main())
