#!/usr/bin/env python3
"""Derive the optional D51 native playback aliases from the included authored ADB.

The ADB establishes exact alias membership in Henry's master/attack fragments.
An AnimLayer's ordinal does NOT establish the runtime skeleton layer. The added
runtime owner is separately constrained to validated Henry, active FIFO layer 0.
No camera, root trajectory, native eligibility or fragment tags are rewritten.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
MEMBER = 'Animations/Mannequin/ADB/kcd_male_combat_generated.adb'
EXPECTED_SHA256 = 'b0e2d9d519045327a752c57a75677fc064d660e12480cae5104a01881c721e75'
GROUPS = ('CombatMasterStrikeGen', 'CombatAttackComboGen')


def generate():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pak', type=Path, default=ROOT / 'companion/C63_UNIFIED/Mods/KCD2VR/Data/KCD2VR.pak')
    parser.add_argument('--header', type=Path, default=ROOT / 'src/subsystems/masterstrike_combos/native_paired_aliases_d51.h')
    parser.add_argument('--evidence', type=Path, default=ROOT / 'repair_evidence/d51/combat/native_paired_aliases_d51.json')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with ZipFile(args.pak) as pak:
        authored = pak.read(MEMBER)
    digest = hashlib.sha256(authored).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit('Authored ADB hash differs: inspect the asset before regenerating this exact allowlist.')
    root = ET.fromstring(authored)
    rows, stats = [], {}
    for group in GROUPS:
        fragments = root.find('FragmentList/' + group)
        if fragments is None:
            raise SystemExit('Missing authored fragment group: ' + group)
        group_aliases = set()
        empty = 0
        for fragment in fragments:
            layers = fragment.findall('AnimLayer')
            if not layers:
                empty += 1
                continue
            # Both inspected source groups have precisely one authored layer
            # whenever animated; reject a future asset with ambiguous layers.
            if len(layers) != 1:
                raise SystemExit('Expected exactly one authored AnimLayer: ' + group)
            for animation in layers[0].findall('Animation'):
                name = animation.attrib.get('name', '')
                if not name.startswith('combat_') or not name.endswith(('_master', '_solo')):
                    raise SystemExit('Unexpected side/alias: ' + name)
                group_aliases.add(name)
                rows.append({
                    'group': group, 'guid': fragment.attrib.get('GUID', ''),
                    'tags': fragment.attrib.get('Tags', ''),
                    'fragment_tags': fragment.attrib.get('FragTags', ''),
                    'authored_anim_layer_ordinal': 0,
                    'authored_anim_layer_count': len(layers), 'alias': name,
                })
        stats[group] = {'fragments': len(fragments), 'without_animation_layer': empty,
                        'unique_aliases': len(group_aliases)}
    aliases = sorted({r['alias'] for r in rows})
    if len(aliases) != 153:
        raise SystemExit('Unexpected alias count: ' + str(len(aliases)))
    header = '''#pragma once
// Generated by tools/generate_native_paired_aliases_d51.py. Exact authored
// Henry master/attack aliases from the included kcd_male_combat_generated.adb.
// ADB member SHA256: ''' + digest + '''
// Authored AnimLayer ordinal is not a runtime layer claim. The caller must
// require fallback ON + validated Henry + active runtime FIFO layer 0.
// Existing NativeBodyAlias112 stays the baseline when the backup is OFF.
#include <cstddef>
#include <cstring>
namespace kcd2vr::native_paired_aliases_d51 {
inline constexpr const char* aliases[]{
''' + ''.join('    "' + n + '",\n' for n in aliases) + '''};
inline constexpr std::size_t count=sizeof(aliases)/sizeof(aliases[0]);
inline bool contains(const char* name) noexcept {
    if(!name)return false;
    std::size_t lo=0,hi=count;
    while(lo<hi){const auto mid=lo+(hi-lo)/2;const int cmp=std::strcmp(name,aliases[mid]);
        if(!cmp)return true;
        if(cmp<0)hi=mid;else lo=mid+1;}
    return false;
}
}
'''
    evidence = {
        'source': 'companion/C63_UNIFIED/Mods/KCD2VR/Data/KCD2VR.pak',
        'member': MEMBER, 'member_sha256': digest,
        'authority': 'Exact authored fragment alias membership; no runtime/controllerdefs layer inference',
        'runtime_guard': 'Selected backup; validated Henry skeleton; active runtime FIFO layer 0',
        'runtime_layer_mapping': 'Conservative layer-0 eligibility; controllerdefs not independently decoded here',
        'unchanged': ['Original fragment tags/selection/RPG predicates', 'Original camera/root procedures',
                      'Existing NativeBodyAlias112 baseline'],
        'groups': stats, 'unique_aliases': len(aliases), 'memberships': rows,
    }
    expected = ((args.header, header), (args.evidence, json.dumps(evidence, indent=2) + '\n'))
    for path, content in expected:
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit('Generated file differs: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('D51 authored native aliases:', len(aliases), 'member SHA256:', digest,
          'mode:', 'verified' if args.check else 'generated')


if __name__ == '__main__':
    generate()
