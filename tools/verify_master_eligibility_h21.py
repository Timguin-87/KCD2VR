"""Generate/check exact-retail, read-only master eligibility hook contracts."""
import argparse, hashlib, json, pathlib, sys, re
DEPS=pathlib.Path('C:/Users/turcs/.codex/worktrees/d514/KCD2VR/review-r59_5-2026-10-11/deps')
sys.path.insert(0,str(DEPS))
import pefile, capstone
SHA='bdf8f9e4a11257a72b64c84700e284c29e4c4ccaf5b8d4bfa7d0b2a7294479f7'
MID=[0x90A5DC,0x90A5FD,0x90A61B,0x90A62C,0x90A64C,0x90A663,0x90A6A8,0x90A6C9,0x90A6E9]
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--binary',default='C:/Steam/steamapps/common/KingdomComeDeliverance2/Bin/Win64MasterMasterSteamPGO/WHGame.dll')
    ap.add_argument('--write-header',action='store_true');ap.add_argument('--out',required=True);a=ap.parse_args()
    data=pathlib.Path(a.binary).read_bytes();assert hashlib.sha256(data).hexdigest()==SHA
    pe=pefile.PE(data=data);assert pe.FILE_HEADER.TimeDateStamp==0x6A350E20
    functions={e.struct.BeginAddress:e.struct.EndAddress for e in pe.DIRECTORY_ENTRY_EXCEPTION}
    assert functions[0x90A59C]==0x90A70E and functions[0x17FD570]==0x17FD5A0
    md=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_64);base=pe.OPTIONAL_HEADER.ImageBase
    md.detail=True
    instructions=list(md.disasm(pe.get_data(0x90A59C,0x172),base+0x90A59C));starts={x.address-base for x in instructions}
    assert all(x in starts for x in MID)
    def span(site,width):
        n=0
        for x in md.disasm(pe.get_data(site,40),base+site):
            n+=x.size
            if n>=width:return n
        raise AssertionError(('incomplete displacement',hex(site),width))
    def hazards(site,width):
        end=site+span(site,width); found=[]
        for x in instructions:
            if not (x.mnemonic.startswith('j') or x.mnemonic=='call'):continue
            if not x.operands or x.operands[0].type!=capstone.x86.X86_OP_IMM:continue
            origin=x.address-base;target=x.operands[0].imm-base
            if site<target<end and not site<=origin<end:
                found.append({'origin':hex(origin),'target':hex(target)})
        return found
    # Regression witnesses from both crashes. Exact native branches entered
    # bytes overwritten by the old compare-site hooks, even with near jumps.
    old_hazards={f'{site:X}/{width}':hazards(site,width)
                 for site,width in [(0x90A6E5,5),(0x90A6E5,14),(0x90A65B,14)]}
    assert all(old_hazards.values()),'old unsafe-site regression witness lost'
    spans=[]
    for width in (5,14):
        for i,site in enumerate(MID):
            n=span(site,width)
            assert i+1==len(MID) or site+n<=MID[i+1], (hex(site),n,'overlapping hook spans')
            edges=hazards(site,width)
            assert not edges,(hex(site),width,'outside native branch enters displaced interior',edges)
            spans.append({'site':hex(site),'patch_width':width,'instruction_span':n,'inbound_interior_edges':edges})
    # Existing real tests, inversion, and final candidate dispatch. No guessed ABI.
    expected={0x90A5D7:'e8c4e7ffff',0x90A5F8:'e82f700c00',0x90A615:'ff9078010000',
              0x90A627:'e80440e2ff',0x90A64E:'7513',0x90A656:'e8d16f0c00',0x90A65D:'0f8599000000',
              0x90A6A3:'e830c03400',0x90A6B0:'e8bb2eef00',0x90A6C4:'e817e6b9ff',
              0x90A6E0:'e873c14400',0x90A6E7:'7413',0x90A6EF:'ff9098000000',0x909C67:'ff9090000000'}
    for r,h in expected.items():assert pe.get_data(r,len(bytes.fromhex(h)))==bytes.fromhex(h),(hex(r),h)
    sites=[0x90A59C,0x17FD570,*MID,0x909C64,0x90A6EF]
    lines=['#pragma once','// Generated by tools/verify_master_eligibility_h21.py from exact retail SHA '+SHA,
           'struct MasterEligibilityPinH21 {std::uintptr_t rva;std::array<unsigned char,16> bytes;};',
           'static constexpr MasterEligibilityPinH21 kMasterEligibilityPinsH21[]{']
    for site in sites:lines.append('    {0x%X,{%s}},'%(site,','.join('0x%02X'%b for b in pe.get_data(site,16))))
    lines.append('};');header='\n'.join(lines)+'\n'
    path=pathlib.Path(__file__).resolve().parents[1]/'src/vrik/master_eligibility_pins_h21.h'
    if a.write_header:path.write_text(header,encoding='utf-8',newline='\n')
    assert path.read_text(encoding='utf-8')==header,'generated contract differs'
    runtime=(path.parent/'master_eligibility_h21.inl').read_text(encoding='utf-8')
    runtime_sites=re.search(r'constexpr std::uintptr_t sites\[\]\{([^}]+)\}',runtime)
    assert runtime_sites and [int(x,16) for x in re.findall(r'0x[0-9A-Fa-f]+',runtime_sites.group(1))]==MID,'production mid sites differ from verified CFG'
    mid_names=re.findall(r'"(kcd2vr_ms_[a-z_0-9]+)"',runtime)
    assert len(mid_names)==len(MID) and len(set(mid_names))==len(MID),'native hook registry names must be distinct'
    out=pathlib.Path(a.out);out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(json.dumps({'status':'PASS','retail_sha256':SHA,'timestamp':'0x6A350E20','functions':{'90A59C':'90A70E','17FD570':'17FD5A0'},
        'pins':len(sites),'native_edges':len(expected),'distinct_mid_hook_names':mid_names,'mid_hook_spans':spans,'old_unsafe_site_regressions':old_hazards,'cfg_scope':'all direct edges in exact native eligibility function; near5 and absolute14 displacements','native_execution':'NOT_RUN'},indent=2)+'\n')
    print('PASS exact retail master eligibility contract:',len(sites),'pins;',len(expected),'native edges')
if __name__=='__main__':main()
