def unique(source, anchor):
    hits = [m.start() for m in re.finditer(re.escape(anchor), source)]
    if len(hits) != 1:
        raise RuntimeError(f"Expected one production anchor ({len(hits)}): {anchor}")
    return hits[0]


def closing_brace(source, start):
    """Return a C++ block's end, ignoring braces in strings and comments."""
    begin = source.index("{", start)
    depth = 0
    quote = comment = None
    i = begin
    while i < len(source):
        c, pair = source[i], source[i:i+2]
        if comment == "line":
            if c == "\n":
                comment = None
        elif comment == "block":
            if pair == "*/":
                comment = None
                i += 1
        elif quote:
            if c == "\\":
                i += 1
            elif c == quote:
                quote = None
        elif pair == "//":
            comment = "line"
            i += 1
        elif pair == "/*":
            comment = "block"
            i += 1
        elif c in ('"', "'"):
            quote = c
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise RuntimeError("Unterminated production block")


def function(name, source_name, anchor):
    source = sources[source_name]
    start = unique(source, anchor)
    return name, source_name, start, closing_brace(source, start)


def write_generated(filename, parts):
    content = ["// Generated by tools/extract_fist_transport175.py; do not edit.\n"]
    records = []
    for name, source_name, start, end in parts:
        source = sources[source_name]
        snippet = source[start:end]
        line = source.count("\n", 0, start) + 1
        content += [f'\n#line {line} "{source_name}"\n', snippet, "\n"]
        records.append({"clause": name, "source": source_name, "source_line": line,
                        "sha256": hashlib.sha256(snippet.encode()).hexdigest()})
    content.append(f'\n#line 1 "{filename}"\n')
    (ROOT / filename).write_text("".join(content))
    return {"generated": filename, "clauses": records}


