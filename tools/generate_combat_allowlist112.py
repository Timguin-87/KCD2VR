"""Derive conservative visual ownership from the supplied retail ADB archive.

An alias reused outside an ordinary on-foot fragment is deliberately ambiguous.
This establishes asset/layer provenance, not absence of CAF gameplay events.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ADB = 'Mannequin/ADB/kcd_male_combat_database.adb'
DEFS = 'Mannequin/ADB/kcd_male_controllerdefs.xml'
FRAGMENTS = {'FreeAttack', 'FreeAttackStart', 'FreeBlock', 'CombatClenchedHand'}


def derive(archive):
    candidates, denied, hashes, protected = {}, set(), {}, set()
    with zipfile.ZipFile(archive) as z:
        defs = ET.fromstring(z.read(DEFS))
        scopes = defs.find('ScopeDefs')
        for name, layer in [('UpperBody', 6), ('HoldItemRight', 4), ('HoldItemLeft', 3)]:
            assert int(scopes.find(name).get('layer')) == layer
        hashes[DEFS] = hashlib.sha256(z.read(DEFS)).hexdigest()
        for path in sorted(z.namelist()):
            if not path.lower().endswith('.adb'):
                continue
            data = z.read(path)
            hashes[path] = hashlib.sha256(data).hexdigest()
            root = ET.fromstring(data)
            for group in root:
                if group.tag != 'FragmentList':
                    denied.update(a.get('name', '') for a in group.iter('Animation'))
                    continue
                for entry in group:
                    for frag in entry:
                        tags = (str(frag.attrib)).lower()
                        for layer in frag.findall('AnimLayer'):
                            for anim in layer.findall('Animation'):
                                name = anim.get('name', '')
                                # These native actions own Henry's body while their
                                # real FIFO entries are active; no name-based timer.
                                if name and path.rsplit('/', 1)[-1].startswith('kcd_male') and (
                                    any(x in entry.tag.lower() for x in
                                        ('hit', 'clinch', 'sync', 'mercy', 'death', 'stealth', 'horse'))
                                    or 'horse' in tags):
                                    protected.add(name)
                                eligible = (name and path == ADB and entry.tag in FRAGMENTS
                                    and layer is frag.find('AnimLayer') and not any(
                                        x in tags + name.lower() for x in
                                        ('horse', 'kick', 'sync', 'bow', 'clinch', 'finish')))
                                if not eligible:
                                    denied.add(name)
                                    continue
                                definition = defs.find('FragmentDefs').find(entry.tag)
                                relevant = [definition] + [o for o in definition if not any(
                                    x in str(o.attrib).lower() for x in ('horse', 'kick'))]
                                expected = 'HoldItem' if entry.tag == 'CombatClenchedHand' else 'UpperBody'
                                assert all(o.get('scopes', '').startswith(expected) or
                                           (entry.tag == 'CombatClenchedHand' and o is definition)
                                           for o in relevant)
                                native_layer = 6
                                if entry.tag == 'CombatClenchedHand':
                                    assert frag.get('Tags') == 'l_noweapon+r_noweapon'
                                    native_layer = {'aZ1': 4, 'aZ2': 3}[frag.get('FragTags')]
                                candidates.setdefault(name, set()).add(native_layer)
    entries = {n: sorted(l) for n, l in sorted(candidates.items()) if n not in denied}
    return entries, {'source_sha256': hashes, 'entries': entries, 'native_body_aliases': sorted(protected),
                     'shared_aliases_rejected': sorted(candidates.keys() & denied)}


def render(entries, protected):
    rows = ''.join('    {"%s", %du},\n' % (n, sum(1 << l for l in layers))
                   for n, layers in entries.items())
    return ('// Generated by tools/generate_combat_allowlist112.py; exact aliases only.\n'
            '#pragma once\nnamespace kcd2vr::vr_combat111 {\n'
            'struct VisualAlias112 { const char* name; unsigned layers; };\n'
            'inline constexpr VisualAlias112 kVisualAliases112[]{\n' + rows + '};\n'
            'inline constexpr const char* kNativeBodyAliases112[]{\n' +
            ''.join('    "%s",\n' % n for n in protected) + '};\n}\n')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('archive')
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    entries, evidence = derive(args.archive)
    outputs = {ROOT / 'src/vrik/combat_visual_aliases112.h': render(entries, evidence['native_body_aliases']),
               ROOT / 'tests/fixtures/combat_visual_aliases112.json': json.dumps(evidence, indent=2) + '\n'}
    for path, content in outputs.items():
        if args.check:
            assert path.read_text() == content, path
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f'{len(entries)} unambiguous aliases; {len(evidence["source_sha256"])} source files checked')
