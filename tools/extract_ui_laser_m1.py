"""Extract actual XR flat-pointer math/submit-plane prefix for the host fixture.

No game/DLL execution. Native UI classification and OpenXR submission remain
runtime boundaries; the fixture tests the production math under setter churn.
"""
import sys as _m2_source_sys
from pathlib import Path as _M2SourcePath
_m2_source_sys.path.insert(0, str(_M2SourcePath(__file__).resolve().parents[1] / "tools"))
from source_text import read_source, read_source_bytes
import argparse
import hashlib
import json
from pathlib import Path


def between(text, first, last):
    start = text.index(first)
    return text[start:text.index(last, start)]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parents[1] / "src/xr_manager.cpp")
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "tests")
    args = parser.parse_args()
    source = read_source(args.source, encoding="utf-8-sig")
    math = between(source, "struct V3f {", "\n\n\n}\n\n\nnamespace {")
    pointer = between(source, "    const float ui88_distance=", "    // Standalone loot/transfer")
    capture = "    auto presentation59c2=CapturePresentation59c2();\n"
    assert source.count(capture.strip()) == 1
    assert source.index(capture.strip()) < source.index(pointer.strip())
    for mutable in ("flat_ui_mode_.load", "native_menu_plane_mode_.load", "physical_map_mode_.load", "flat_ui_anchor_pose_"):
        assert mutable not in pointer, f"mutable hit-plane read: {mutable}"
    assert "presentation59c2.anchor" in pointer
    panel = between(source, "    const bool physical_map_requested = presentation59c2.policy.physical_map;", "            flat_game_quad.space = local_space_;")
    # Close the two actual native flat-panel guards after recording their pose.
    panel += "            panelCentre={anchor.position.x+forward.x,anchor.position.y+forward.y,anchor.position.z+forward.z};\n"
    panel += "            panelQ=level_q;panelReady=true;\n        }\n    }\n"
    cancel = between(source, "    if(!production_presentation59c2_.Current(presentation59c2.ticket)){", "    const XrCompositionLayerBaseHeader* layers[12]{};")
    members = {
        "generated_ui_laser_math_m1.inc": math,
        "generated_ui_laser_pointer_m1.inc": capture + pointer,
        "generated_ui_laser_panel_m1.inc": panel,
        "generated_ui_laser_cancel_m1.inc": cancel,
    }
    args.out.mkdir(parents=True, exist_ok=True)
    receipt = {"source": "src/xr_manager.cpp", "source_sha256": hashlib.sha256(read_source_bytes(args.source)).hexdigest(),
               "meaning": "Actual production hit-test and panel-prefix extraction; not a headset/OpenXR execution proof", "members": {}}
    for name, body in members.items():
        payload = ("// Generated by tools/extract_ui_laser_m1.py; do not edit.\n" + body).encode("utf-8")
        (args.out / name).write_bytes(payload)
        receipt["members"][name] = hashlib.sha256(payload).hexdigest()
    (args.out / "ui_laser_frame_m1.provenance.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
