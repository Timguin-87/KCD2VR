"""Generate the extra retail caller contract from the supplied, exact WHGame.dll."""
import hashlib,struct,sys
from pathlib import Path
path=Path(sys.argv[1] if len(sys.argv)>1 else 'C:/Steam/steamapps/common/KingdomComeDeliverance2/Bin/Win64MasterMasterSteamPGO/WHGame.dll')
b=path.read_bytes()
assert hashlib.sha256(b).hexdigest()=='bdf8f9e4a11257a72b64c84700e284c29e4c4ccaf5b8d4bfa7d0b2a7294479f7'
pe=struct.unpack_from('<I',b,60)[0];n=struct.unpack_from('<H',b,pe+6)[0];optional=struct.unpack_from('<H',b,pe+20)[0]
assert struct.unpack_from('<I',b,pe+8)[0]==0x6A350E20
sections=[struct.unpack_from('<IIII',b,pe+24+optional+i*40+8) for i in range(n)]
def read(rva,count):
 for vs,va,size,raw in sections:
  if va<=rva and rva+count<=va+size:return b[raw+rva-va:raw+rva-va+count]
 raise ValueError(hex(rva))
out=['// Generated by tools/generate_admission147.py from the exact SHA. Do not hand-edit.',
 'static bool PredictionAdmissionContract147(std::uintptr_t b) noexcept {',
 '    if(!b||!retail_build112::Ready(b))return false;']
for i,(rva,size) in enumerate([(0xA7CDDF,15),(0xA7EC9D,49)]):
 data=read(rva,size)
 out += ['    const unsigned char expected%d[]{%s};'%(i,','.join('0x%02X'%v for v in data)),
         '    unsigned char actual%d[%d]{};'%(i,size),
         '    if(!Read(reinterpret_cast<void*>(b+0x%X),actual%d)||std::memcmp(actual%d,expected%d,%d))return false;'%(rva,i,i,i,size)]
out+=['    return true;','}']
dest=Path(__file__).resolve().parents[1]/'src/vrik/prediction_admission_contract147.inl'
dest.write_text('\n'.join(out)+'\n',encoding='utf-8')
print(dest)
