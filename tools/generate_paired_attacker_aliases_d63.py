#!/usr/bin/env python3
"""Pin attacker-only paired playback aliases to the shipped retail ADB.

The table grants no native action, root motion, hit or timing permission. It
only identifies the player's known attacker clip when deciding VR arm/body
presentation with the user's native-animation preference OFF.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
MEMBER = 'Animations/Mannequin/ADB/kcd_male_combat_generated.adb'
EXPECTED = 'b0e2d9d519045327a752c57a75677fc064d660e12480cae5104a01881c721e75'
GROUPS = ('CombatMasterStrikeGen', 'CombatMasterStrikeDeathGen',
          'CombatAttackComboGen', 'CombatAttackComboDeathGen')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pak', type=Path, default=ROOT / 'companion/C63_UNIFIED/Mods/KCD2VR/Data/KCD2VR.pak')
    parser.add_argument('--header', type=Path, default=ROOT / 'src/subsystems/masterstrike_combos/paired_attacker_aliases_d63.h')
    parser.add_argument('--evidence', type=Path, default=ROOT / 'repair_evidence/d63/combat/paired_attacker_aliases_d63.json')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with ZipFile(args.pak) as pak:
        data = pak.read(MEMBER)
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED:
        raise SystemExit('The pinned ADB changed; re-review its membership before regenerating.')
    tree = ET.fromstring(data)
    rows, stats = [], {}
    for group in GROUPS:
        fragments = tree.find('FragmentList/' + group)
        if fragments is None:
            raise SystemExit('Missing fragment group: ' + group)
        names, empty = set(), 0
        for fragment in fragments:
            layers = fragment.findall('AnimLayer')
            if not layers:
                empty += 1
                continue
            if len(layers) != 1:
                raise SystemExit('Ambiguous authored layers: ' + group)
            for animation in layers[0].findall('Animation'):
                name = animation.get('name', '')
                if not name.startswith('combat_') or not name.endswith(('_master', '_solo')):
                    raise SystemExit('Unexpected attacker side: ' + name)
                names.add(name)
                rows.append({'group': group, 'guid': fragment.get('GUID', ''),
                             'tags': fragment.get('Tags', ''), 'alias': name})
        stats[group] = {'fragments': len(fragments), 'empty': empty, 'aliases': len(names)}
    names = sorted({row['alias'] for row in rows})
    header = '''#pragma once
// Generated by tools/generate_paired_attacker_aliases_d63.py.
// Exact attacker-only membership in the four masterstrike/combo Gen/DeathGen
// groups of the pinned retail ADB. Native events and victim clips are unchanged.
// ADB SHA256: ''' + digest + '''
// Authored layer ordinal is not runtime-layer evidence: the consumer requires
// validated Henry, active runtime FIFO layer 0 and native animation backup OFF.
#include <cstddef>
#include <cstring>
namespace kcd2vr::paired_attacker_aliases_d63 {
inline constexpr const char* aliases[]{
''' + ''.join('    "' + name + '",\n' for name in names) + '''};
inline constexpr std::size_t count=sizeof(aliases)/sizeof(aliases[0]);
inline bool contains(const char* name) noexcept {
    if(!name)return false;
    std::size_t lo=0,hi=count;
    while(lo<hi){const auto mid=lo+(hi-lo)/2;const int c=std::strcmp(name,aliases[mid]);
        if(!c)return true;if(c<0)hi=mid;else lo=mid+1;}
    return false;
}
}
'''
    evidence = {'member': MEMBER, 'sha256': digest, 'groups': stats,
                'aliases': len(names), 'memberships': rows,
                'authority': 'Exact attacker alias membership; no native pair/action/hit join or runtime layer inference'}
    for path, content in ((args.header, header), (args.evidence, json.dumps(evidence, indent=2) + '\n')):
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit('Generated output differs: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('D63 exact paired attacker aliases:', len(names), 'ADB:', digest)


if __name__ == '__main__':
    main()
