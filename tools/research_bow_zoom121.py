"""Verify the retail aim-zoom calculation and its camera-only consumer offline."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from capstone import Cs, CS_ARCH_X86, CS_MODE_64
from native_research112 import PE
from research_prediction119 import EXPECTED


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--whgame',type=Path,required=True)
    ap.add_argument('--out',type=Path,required=True);ap.add_argument('--header',type=Path)
    a=ap.parse_args();pe=PE(a.whgame)
    assert hashlib.sha256(pe.data).hexdigest()==EXPECTED and pe.stamp==0x6A350E20
    assert struct.unpack('<Q',pe.read(0x3AE44B8,8))[0]==pe.base+0x2CEEAAC
    assert pe.read(0x10610B6,3)==bytes.fromhex('41ffd1') # call r9; returns at B9
    assert pe.read(0x10610B9,3)==bytes.fromhex('0f28f0') # result -> xmm6
    assert pe.read(0x10610CA,4)==bytes.fromhex('f30f5ec6') # FOV /= xmm6
    assert pe.read(0x10610CE,5)==bytes.fromhex('f30f114630') # sole FOV store
    assert struct.unpack('<f',pe.read(0x4099F44,4))[0]==1.0
    dis=Cs(CS_ARCH_X86,CS_MODE_64);a.out.mkdir(parents=True,exist_ok=True)
    for rva in (0x2CEEAAC,0x106103C):
        start,end=pe.function(rva)
        text=''.join(f'{i.address-pe.base:08X} {i.mnemonic} {i.op_str}\n' for i in dis.disasm(pe.read(start,end-start),pe.base+start))
        (a.out/f'{rva:X}.asm').write_text(text,encoding='utf-8')
    # RPG registration pairs are supporting evidence, never patched parameters.
    start,end=0xCEAA73,0xCEAB53
    (a.out/'aim_parameter_registration.asm').write_text(''.join(f'{i.address-pe.base:08X} {i.mnemonic} {i.op_str}\n' for i in dis.disasm(pe.read(start,end-start),pe.base+start)),encoding='utf-8')
    pins={0x2CEEAAC:24,0x1061099:32,0x10610B9:26,0x3AE44B8:8}
    # The vtable entry is relocated at runtime; qualify it as a base-relative pointer.
    header=['// Generated by tools/research_bow_zoom121.py against the exact retail SHA.',
            'static bool BowZoomContract121(std::uintptr_t b) noexcept {',
            '    if(!b||!SupportedWhBuild(b)||!retail_build112::Ready(b))return false;']
    for n,(rva,size) in enumerate(list(pins.items())[:-1]):
        raw=pe.read(rva,size)
        header += [f'    const unsigned char expected{n}[]{{'+','.join(f'0x{x:02X}' for x in raw)+'};',
                   f'    unsigned char actual{n}[{size}]{{}};',
                   f'    if(!Read(reinterpret_cast<void*>(b+0x{rva:X}),actual{n})||std::memcmp(actual{n},expected{n},{size}))return false;']
    header += ['    std::uintptr_t fn=0;return Read(reinterpret_cast<void*>(b+0x3AE44B8),fn)&&fn==b+0x2CEEAAC;','}']
    text='\n'.join(header)+'\n';(a.out/'bow_zoom_contract121.inl').write_text(text,encoding='utf-8')
    if a.header:a.header.write_text(text,encoding='utf-8')
    report=dict(result='PASS',sha256=EXPECTED,timestamp='6A350E20',
                pins={f'{r:X}':pe.read(r,s).hex() for r,s in pins.items()},
                rpg_vtable='3AE4410',method_byte_offset='A8',rpg_function='2CEEAAC',
                camera_function='106103C',camera_call_return='10610B9',
                signature='float (RPGCombat* RCX, soul* RDX, uint64 itemKey R8)',
                rpg_formula='below AimZoomBaseSkill: 0; otherwise min((skill-baseSkill)*AimSkillToZoom+AimZoomBase,AimZoomMax)',
                camera_formula='cameraFov /= 1 + zoom * blend',
                override='camera caller only: return zero after original calculation; native blend and player+2C8 update untouched',
                limitations=['Static ABI/data-flow proof; runtime detour relocation and headset result untested.'])
    (a.out/'bow-zoom-contract.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,indent=2))


if __name__=='__main__':main()
