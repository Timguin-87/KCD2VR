"""Generate exact-byte pins for passive contact-filter / target-body observers."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from capstone import Cs, CS_ARCH_X86, CS_MODE_64
from native_research112 import PE
from research_prediction119 import EXPECTED


def main():
    p=argparse.ArgumentParser();p.add_argument('--whgame',type=Path,required=True);p.add_argument('--out',type=Path,required=True)
    p.add_argument('--headers',type=Path);a=p.parse_args();pe=PE(a.whgame)
    assert hashlib.sha256(pe.data).hexdigest()==EXPECTED and pe.stamp==0x6A350E20
    cs=Cs(CS_ARCH_X86,CS_MODE_64)
    stages={0xD51910:('test','al, al'),0xD51925:('test','al, al'),0xD5193E:('test','al, al'),
            0xD5195D:('cmp','byte ptr [rsp + 0x30], 0'),0xD51A26:('test','dl, dl')}
    for rva,pair in stages.items():
        i=next(cs.disasm(pe.read(rva,16),rva));assert (i.mnemonic,i.op_str)==pair
    for site,target in {0xD5190B:0xD51B38,0xD51920:0xD51ACC,0xD51939:0xD52340,0xD51958:0xD53024,0x8A4A0A:0x5D70C4,0x37CFD23:0x8A49FC}.items():
        raw=pe.read(site,5);assert raw[0]==0xE8 and site+5+struct.unpack('<i',raw[1:])[0]==target
    assert struct.unpack('<Q',pe.read(0x4072C78+0x278,8))[0]==pe.base+0x8A49FC
    # Copied candidate ends before the stage-4 observer; record address is NOT a health/damage boundary.
    i=next(cs.disasm(pe.read(0xD51A22,16),0xD51A22));assert (i.mnemonic,i.op_str)==('mov','qword ptr [rcx + 0x50], rax')
    a.out.mkdir(parents=True,exist_ok=True);reports=[]
    for begin,end in [(0xD51854,0xD51ACC),(0x8A49FC,0x8A4A6A),(0x37CFD1B,0x37CFD3C)]:
        raw=pe.read(begin,end-begin);name=f'{begin:X}.asm'
        (a.out/name).write_text('\n'.join(f'{i.address:08X} {i.mnemonic} {i.op_str}'.rstrip() for i in cs.disasm(raw,begin))+'\n',encoding='utf-8')
        reports.append(dict(rva=f'{begin:X}',bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest(),listing=name))
    def generate(name,pins,contact):
        lines=['// Generated by tools/research_physical122.py; exact retail SHA required.',f'static bool {name}(std::uintptr_t b) noexcept {{',
               '    if(!b||!retail_build112::Ready(b))return false;']
        for n,(rva,size) in enumerate(pins.items()):
            raw=pe.read(rva,size)
            lines += [f'    const unsigned char expected{n}[]{{'+','.join(f'0x{x:02X}' for x in raw)+'};',f'    unsigned char actual{n}[{size}]{{}};']
            read=f'ReadCopy6689(reinterpret_cast<void*>(b+0x{rva:X}),actual{n},{size})' if contact else f'Read(reinterpret_cast<void*>(b+0x{rva:X}),actual{n})'
            lines += [f'    if(!{read}||std::memcmp(actual{n},expected{n},{size}))return false;']
        if not contact:lines+=['    std::uintptr_t method=0;if(!Read(reinterpret_cast<void*>(b+0x4072EF0),method)||method!=b+0x8A49FC)return false;']
        lines+=['    return true;','}'];return '\n'.join(lines)+'\n'
    headers={'diagnostics/contact_path_contract122.inl':generate('ContactPathContract122',{r:8 for r in stages},True),
             'vrik/interaction_body_contract122.inl':generate('InteractionBodyContract122',{0x8A49FC:16,0x37CFD23:5},False)}
    for name,source in headers.items():
        (a.out/Path(name).name).write_text(source,encoding='utf-8')
        if a.headers:(a.headers/name).write_text(source,encoding='utf-8')
    report=dict(result='PASS',sha256=EXPECTED,timestamp='6A350E20',ranges=reports,stage_sites=[f'{x:X}' for x in stages],
                boundary='Read-only register/result observation; originals unchanged',
                limitations=['Copied collision candidate is not accepted damage.','Entity physics getter returns are not constraint creation or release proof.','No relative contact velocity ABI or physical hand proxy lifecycle certified.'])
    (a.out/'static-contract.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8');print('PASS physical122 static contracts')


if __name__=='__main__':main()
