enum class MaskStatus:unsigned char {Unknown,Ready,Unreadable,Empty,TooLarge,Changed,UnknownMissileClass,BitZero};
struct MaskReceipt {
    std::uintptr_t entries=0;
    std::uint64_t count=0;
    std::uint32_t missileItems=0;
    MaskStatus status=MaskStatus::Unknown;
};
// Exact loaded ItemClass registry schema: registered ItemManager.GetItemName
// 2ABC25C uses WH+5325820 ->468340, which reads vector+78/count+80, stride24,
// definition at entry+10. MissileItem+108 returns this;476358 reads class+E8.
// Only the existing native owner may run this bounded readiness-edge scan.
// The getter callbacks never enumerate a registry or invoke a native service.
template<class Reader>
MaskReceipt inspectMasks(std::uintptr_t base,Reader&& read) noexcept {
    MaskReceipt out{};
    const auto registry=base+itemRegistry;
    if(!base||!read(registry+0x78,&out.entries,sizeof(out.entries))||
       !read(registry+0x80,&out.count,sizeof(out.count))){out.status=MaskStatus::Unreadable;return out;}
    if(!out.entries||!out.count){out.status=MaskStatus::Empty;return out;}
    if(out.count>65536){out.status=MaskStatus::TooLarge;return out;}
    if(out.entries>~std::uintptr_t(0)-out.count*24){out.status=MaskStatus::Unreadable;return out;}
    for(std::uint64_t i=0;i<out.count;++i){
        std::uintptr_t row=0,vft=0;
        if(!read(out.entries+i*24+0x10,&row,sizeof(row))||!row||
           !read(row,&vft,sizeof(vft))){out.status=MaskStatus::Unreadable;return out;}
        if(vft!=base+missileItemVft)continue;
        std::uintptr_t metadata=0,metadataVft=0;unsigned char mask=0;
        if(!read(row+0xE8,&metadata,sizeof(metadata))||!metadata||
           !read(metadata,&metadataVft,sizeof(metadataVft))||
           !read(metadata+0x98,&mask,sizeof(mask))){out.status=MaskStatus::Unreadable;return out;}
        if(metadataVft!=base+missileClassVft){out.status=MaskStatus::UnknownMissileClass;return out;}
        if(mask&1){out.status=MaskStatus::BitZero;return out;}
        ++out.missileItems;
    }
    std::uintptr_t after=0;std::uint64_t afterCount=0;
    if(!read(registry+0x78,&after,sizeof(after))||!read(registry+0x80,&afterCount,sizeof(afterCount))){
        out.status=MaskStatus::Unreadable;return out;
    }
    if(after!=out.entries||afterCount!=out.count){out.status=MaskStatus::Changed;return out;}
    out.status=out.missileItems?MaskStatus::Ready:MaskStatus::Empty;
    return out;
}
