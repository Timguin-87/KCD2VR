-- H41: explicit console checks use the same proven original object-only
-- scope and completion observer, never a synthetic controller/body request.
local function consoleDoorH41(actor)
  local p=actor:GetWorldPos()
  if not vector(p) then return nil end
  local list=System.GetEntitiesInSphere(p,2.35)
  local best,dist
  for _,e in pairs(list or {}) do
    if type(e)=='table' and e.class=='AnimDoor' and type(e.GetWorldBBox)=='function' then
      local a,b=e:GetWorldBBox()
      if vector(a) and vector(b) then
        local d=distance(p,a,b)
        if d<=2.35 and (not dist or d<dist) then best,dist=e,d end
      end
    end
  end
  return best
end
local function queueTestH41(value)
  local actor=rawget(_G,'player') or rawget(_G,'g_localActor')
  if not D.installed or not actor or actor.id==nil or System.GetEntity(actor.id)~=actor then return false,'current player unavailable' end
  local e=consoleDoorH41(actor)
  if not e or System.GetEntity(e.id)~=e then return false,'no current nearby door' end
  if D.testsH41[e] then return false,'original console episode still pending' end
  for side=0,1 do if D.hands[side] and D.hands[side].door==e then return false,'physical hand already owns door' end end
  for i=1,2 do if D.restsH43[i] and D.restsH43[i].door==e then return false,'original partial operation still owned' end end
  local allowed,why=eligibleDoorH41(e,actor)
  if not allowed then return false,why end
  if type(e.curAnim)~='string' or e.curAnim~='' or e.bNeedUpdate~=0 then return false,'original clip not idle' end
  local A=rawget(_G,'AnimDoor')
  if not A or A.OnUsed~=nativeUsed or e.OnUsed~=nativeUsed or e.Server.OnUpdate~=A.Server.OnUpdate then return false,'native use/update owner changed' end
  local raw=e:GetRawId()
  if not integer(raw,1,4294967295) or System.GetEntity(raw)~=e then return false,'door identity unavailable' end
  local st={consoleH41=true,side=-1,door=e,doorId=raw,actor=actor,userId=actor.id,playerId=actor.id,
    stage='PENDING',opennessH41=value,retiring=false}
  D.testsH41[e]=st -- ownership published BEFORE wake or reentrant callback
  if not pcall(e.Activate,e,1) then st.failure='test scheduler wake unknown' end
  return true,'queued; native speed and original update own completion'
end
function D.Test(t)
  local value=t==nil and .5 or tonumber(t)
  if not finite(value) then return false,'invalid openness' end
  local ok,result,why=pcall(queueTestH41,math.max(0,math.min(1,value)))
  if not ok then return false,'test request unavailable: '..tostring(result) end
  if captureD48("f5") and System and type(System.LogAlways)=="function" then pcall(System.LogAlways,'KCD2VR_DOOR H41_TEST '..tostring(why)) end
  return result,why
end
