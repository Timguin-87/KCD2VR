  -- A stopped partial door may have a bind/static world bbox. Also consider
  -- its CURRENT carried grab point, without starting or changing that episode.
  -- This is a nomination only; reserve still validates the original native clip.
  if retainedCandidateH44 then
    local e,d=retainedCandidateH44(p)
    if e and (not dist or d<dist) then best,dist=e,d end
  end
  return best
end
-- Per-instance Lua scope only; the captured native component/callable remains
-- the real receiver. A Lua return is not a native signal/body terminal.
local function packScopeH40(...) return { n = select('#', ...), ... } end
local function unpackScopeH40(p, first) return unpack(p, first or 1, p.n) end
local function ownedEpisodeH41(st)
  return st.consoleH41 and D.testsH41[st.door]==st or D.hands[st.side]==st or
    st.restSlotH43 and D.restsH43[st.restSlotH43]==st
end
local function scopeCurrentH40(st)
  local s = st.scope
  return s and ownedEpisodeH41(st) and sameDoor(st) == true and
    st.door.animDoor == s.proxy and st.door.DoPlayAnimation == s.play and
    st.door.SetPhysicalFlags == s.flags and s.proxy.ReportOpened == s.opened and
    s.proxy.ReportClosed == s.closed and s.originalComponent ~= nil
end
local function scopeOriginalClipH40(st)
  local s = st.scope local e = st.door
  return scopeCurrentH40(st) and (s.playReturned or s.joinedNativeH42) and s.playToken and
    e.lastUsedBy == st.userId and e.lastAnim == s.playAnim and e.nDirection == s.playDirection
end
local function scopeClipH40(st)
  return scopeOriginalClipH40(st) and not st.scope.unknown
end
local function unknownScopeH40(st, reason)
  local s = st.scope
  if s then s.unknown = true s.failure = reason end
  st.uncertain = true st.retiring = true
end
local function restoreScopeH40(st)
  local s = st.scope if not s then return end
  local e = st.door
  -- Never replace a successor's field or mutate a global/native method table.
  if rawget(e, 'DoPlayAnimation') == s.play then rawset(e, 'DoPlayAnimation', s.rawPlay) end
  if rawget(e, 'SetPhysicalFlags') == s.flags then rawset(e, 'SetPhysicalFlags', s.rawFlags) end
  if rawget(e, 'animDoor') == s.proxy then rawset(e, 'animDoor', s.rawComponent) end
end
local function installScopeH40(st)
  local e = st.door
  local currentUpdate = type(AnimDoor) == 'table' and type(AnimDoor.Server) == 'table' and AnimDoor.Server.OnUpdate
  local originalUpdate = nativeUpdate(currentUpdate)
  local info = type(debug) == 'table' and debug.getinfo
  local component = e.animDoor
  if type(e) ~= 'table' or type(component) ~= 'table' or type(e.Server) ~= 'table' or e.Server.OnUpdate ~= currentUpdate or
     type(e.DoPlayAnimation) ~= 'function' or type(e.SetPhysicalFlags) ~= 'function' or
     type(component.ReportOpened) ~= 'function' or type(component.ReportClosed) ~= 'function' then
    return false, 'Lua update/component scope unavailable'
  end
  -- Caller metadata strengthens the known callback when available. The actual
  -- per-door update transaction below does not depend on the debug library.
  local s = { originalComponent = component, originalUpdate = originalUpdate, info = info,
    originalPlay = e.DoPlayAnimation, originalFlags = e.SetPhysicalFlags,
    rawPlay = rawget(e, 'DoPlayAnimation'), rawFlags = rawget(e, 'SetPhysicalFlags'), rawComponent = rawget(e, 'animDoor'),
    originalOpened = component.ReportOpened, originalClosed = component.ReportClosed }
  st.scope = s
  local function report(name, original, receiver, userId, caller, ...)
    -- A reentrant attempt of THIS original report cannot invoke the primitive twice.
    if receiver == s.proxy and userId == st.userId and s.reportInFlight and not s.foreignOwnerObserved then
      unknownScopeH40(st, 'reentrant original report') return
    end
    local e = st.door
    if receiver == s.proxy and userId == st.userId and s.updateToken == s.playToken and (not s.originalUpdate or caller == s.originalUpdate) and
       s.reportAttemptToken == s.playToken and not s.foreignOwnerObserved and scopeOriginalClipH40(st) then
      unknownScopeH40(st, 'original report already attempted') return
    end
    local own = receiver == s.proxy and userId == st.userId and s.updateToken == s.playToken and (not s.originalUpdate or caller == s.originalUpdate) and
      scopeClipH40(st) and s.flagReleaseToken == s.playToken and e.curAnim == '' and e.inUse == 0 and
      e.bNeedUpdate == 0 and name == (s.playDirection == -1 and 'ReportClosed' or 'ReportOpened')
    if not own then return original(receiver == s.proxy and s.originalComponent or receiver, userId, ...) end
    if s.reportAttemptToken == s.playToken then unknownScopeH40(st, 'original report already attempted') return end
    local token, entity, actor, component = s.playToken, e, st.actor, s.originalComponent
    s.reportAttemptToken = token s.reportInFlight = true
    -- Store immutable original identity BEFORE the real synchronous call.
    s.reportCall = { token = token, entity = entity, actor = actor, component = component,
      userId = userId, callable = original, name = name }
    local result = packScopeH40(pcall(original, component, userId, ...))
    s.reportInFlight = false
    if not result[1] then unknownScopeH40(st, 'original report threw') error(result[2], 0) end
    s.reportCallReturned = true -- normal Lua binding return, NOT native dispatch/terminal
    if not scopeClipH40(st) or s.playToken ~= token or e ~= entity or st.actor ~= actor or
       s.originalComponent ~= component or e.curAnim ~= '' or e.inUse ~= 0 or e.bNeedUpdate ~= 0 then
      unknownScopeH40(st, 'original report current identity changed')
    else
      s.reportReturnedToken = token
    end
    return unpackScopeH40(result, 2)
  end
  s.proxy = setmetatable({}, { __index = function(_, key)
    local value = component[key]
    if type(value) ~= 'function' then return value end
    -- Other original component bindings always receive their ORIGINAL self.
    return function(receiver, ...) return value(receiver == s.proxy and component or receiver, ...) end
  end })
  s.opened = function(receiver, userId, ...)
    local f = s.info and s.info(2, 'f') return report('ReportOpened', s.originalOpened, receiver, userId, f and f.func, ...)
  end
  s.closed = function(receiver, userId, ...)
    local f = s.info and s.info(2, 'f') return report('ReportClosed', s.originalClosed, receiver, userId, f and f.func, ...)
  end
  s.proxy.ReportOpened = s.opened s.proxy.ReportClosed = s.closed
  s.play = function(receiver, ...)
    local args = packScopeH40(...)
    local caller = s.info and s.info(2, 'f')
    local permit = s.playPermit s.playPermit = nil -- one use; reentrant calls cannot borrow it
    s.playSerial = (s.playSerial or 0) + 1
    local token = {} s.playToken = token s.playReturned = false
    if permit == 'USE' and s.useActive and (not caller or caller.func == nativeUsed) and args[1] == st.direction and args[5] == true then
      args[5] = false args[4] = st.direction == 1 and st.openClip or st.closeClip
    end
    if receiver ~= e or not permit or args[5] ~= false or args[6] ~= st.userId or not scopeCurrentH40(st) then
      s.foreignOwnerObserved = true
      unknownScopeH40(st, 'external native clip call')
      return s.originalPlay(receiver, unpackScopeH40(args))
    end
    local result = packScopeH40(pcall(s.originalPlay, receiver, unpackScopeH40(args)))
    if not result[1] then unknownScopeH40(st, 'original play threw') error(result[2], 0) end
    if not scopeCurrentH40(st) or s.unknown or s.playToken ~= token then unknownScopeH40(st, 'original play current identity changed')
    else
      s.playReturned = true s.playAnim = e.curAnim s.playDirection = e.nDirection
      s.flagReleaseToken = nil s.reportReturnedToken = nil
    end
    return unpackScopeH40(result, 2)
  end
  s.flags = function(receiver, userId, enable, ...)
    local f = s.info and s.info(2, 'f') local e = st.door
    if receiver == e and userId == st.userId and enable == false and s.updateToken == s.playToken and (not s.originalUpdate or f and f.func == s.originalUpdate) and
       scopeOriginalClipH40(st) and not s.foreignOwnerObserved and e.curAnim == '' and e.inUse == 1 and e.bNeedUpdate ~= 0 then
      if st.joinedNativeH42 then
        -- This episode began with the real native player action. Its original
        -- DoPlay acquired Henry's flags, unlike our fresh object-only start.
        -- Let that same original operation perform its matching cleanup.
        local result = packScopeH40(pcall(s.originalFlags, receiver, userId, enable, ...))
        if not result[1] then unknownScopeH40(st, 'joined original flag cleanup threw') error(result[2], 0) end
        s.flagReleaseToken = s.playToken
        return unpackScopeH40(result, 2)
      end
      -- This exact hand-only original clip acquired no actor flag. Skip only
      -- its unmatched release; all other native operations call their original.
      s.flagReleaseToken = s.playToken return
    end
    s.foreignOwnerObserved = true
    unknownScopeH40(st, 'foreign actor flag operation')
    return s.originalFlags(receiver, userId, enable, ...)
  end
  local ok, err = pcall(function()
    rawset(e, 'DoPlayAnimation', s.play) rawset(e, 'SetPhysicalFlags', s.flags) rawset(e, 'animDoor', s.proxy)
  end)
  if not ok then restoreScopeH40(st) st.scope = nil return false, err end
  return true
end
local function ownPlayH40(st, ...)
  local s = st.scope
  if not scopeCurrentH40(st) or s.unknown then error('original Lua operation scope unavailable') end
  s.playPermit = 'PLAY' -- consumed at entry; never held across original native callback
  local result = packScopeH40(pcall(st.door.DoPlayAnimation, st.door, ...))
  s.playPermit = nil
  if not result[1] then error(result[2], 0) end
  if not scopeCurrentH40(st) or s.unknown then error('original play scope changed during call') end
  return unpackScopeH40(result, 2)
end
local function reportReturnedH40(st)
  local s = st.scope
  return scopeClipH40(st) and s.reportReturnedToken == s.playToken and s.reportCallReturned == true
end



-- D48: bounded diagnostic door refusal, only during the explicit F5 capture.
-- D48: query the existing read-only native channel; absent/failed queries stay quiet.
local function captureD48(key)
 local get=System and System.GetCVar
 if type(get)~="function" then return false end
 local ok,value=pcall(get,"kcd2vr_door_capture_"..key)
 return ok and value==1
end
local sayAt=0
local function sayWhy(st)
  if not captureD48("f5") then return end
  if st.consoleH41 or not st.failure or st.said then return end
  st.said=true
  local now=nowMs() or 0
  if now-sayAt<1500 then return end
  sayAt=now
  local msg='door: '..tostring(st.failure)
  if st.failure=='door locked' then msg='door: locked' end
  -- R90: no screen message without F2; the log line below stays (F5).
  if captureD48("f2") and Game and type(Game.SendInfoText)=='function' then pcall(Game.SendInfoText,msg,true,nil,2) end
  if System and System.LogAlways then pcall(System.LogAlways,'KCD2VR_DOOR '..msg) end
end
local function done(st)
  sayWhy(st)
  restoreScopeH40(st)
  if D.hands[st.side]==st then D.hands[st.side]=nil end
  if st.restSlotH43 and D.restsH43[st.restSlotH43]==st then D.restsH43[st.restSlotH43]=nil end
  if st.consoleH41 and D.testsH41[st.door]==st then D.testsH41[st.door]=nil end
end
local function failed(st,reason,unknown)
  st.retiring=true st.failure=reason
  if unknown then st.uncertain=true end
end
local function originalCurrent(st)
  return sameDoor(st)==true and scopeClipH40(st)
end
retainedCandidateH44=function(p)
  local best,dist
  for i=1,2 do
    local st=D.restsH43[i]
    if st and not st.retiring and not st.uncertain and sameActor(st) and originalCurrent(st) and
       st.door.curAnim==st.driveAnim and st.door.nDirection==st.driveDirection and st.clipJoin then
      local ok,point=pcall(function()
        local e=st.door;local actual=e:GetAnimationTime(0,0)
        if not finite(actual) or not timeReadback(e,st.lastClipTime) or not rateReadback(e,0) then return nil end
        local sideName=st.driveAnim:match('door_l') and 'left' or 'right'
        return D.ClipAngleH40.Point(st.clipJoin,actual,e:GetBonePos('Asset_Door-'..sideName),e:GetBonePos('door_'..sideName..'_pivot'))
      end)
      if ok and vector(point) then
        local x,y,z=p.x-point.x,p.y-point.y,p.z-point.z
        local d=math.sqrt(x*x+y*y+z*z)
        if d<=.35 and (not dist or d<dist) then best,dist=st.door,d end
      end
    end
  end
  return best,dist
end
-- Measure achieved native leaf angle between distinct controller feeds, not
-- native frame rate or linear animation time (whose stationary spans vary).
-- A release below .08 rad/s (~4.6 degrees/s), or after motion has gone stale,
-- keeps the partial rest. Normal motion hands back the acquired native clip.
local function resetMotionH44(st,phase,at)
  st.motionAtH44=at st.motionAngleH44=D.ClipAngleH40.At(st.driveAnim,phase)
  st.motionRateH44=0
end
local function sampleMotionH44(st,phase)
  local at=st.feedAt
  if not finite(at) or at==st.motionAtH44 then return end
  local angle=D.ClipAngleH40.At(st.driveAnim,phase)
  local dt=st.motionAtH44 and at-st.motionAtH44
  st.motionRateH44=angle and st.motionAngleH44 and dt and dt>0 and dt<=80 and
    (angle-st.motionAngleH44)*1000/dt or 0
  st.motionAtH44=at st.motionAngleH44=angle
end
local function movingReleaseH44(st,now)
  local recent=finite(now) and finite(st.motionAtH44) and now-st.motionAtH44>=0 and now-st.motionAtH44<=80
  return recent and finite(st.motionRateH44) and math.abs(st.motionRateH44)>.08
end
-- Shared native eligibility for physical hands and explicit console checks.
-- Neither path adopts another original operation or bypasses native lock/key rules.
local function eligibleDoorH41(e,actor,allowNativeUnlock)
  -- Grip owns this hand episode. Native OnUsed retains interactivity/lock
  -- semantics; do not rerun IsUsable (which rejects the same native inUse).
  if e.nDirection~=1 and e.nDirection~=-1 then return false,'native animated direction unavailable' end
  if e.bNoAnims~=false then return false,'native animated door not initialized' end
  -- The retail OnUsed owns key/manual-side unlocking and its native events.
  -- Allow that existing start, never an unlock write or bypass in this script.
  -- Once a clip is ours, a new lock retires hand seeking immediately.
  if e.bLocked==true then
    if allowNativeUnlock==false then return false,'door relocked' end
    if type(e.IsOnKeySide)~='function' or not e.lockBase or
       type(e.lockBase.PlayerHoldsKey)~='function' then return false,'native lock eligibility unavailable' end
    local side=e:IsOnKeySide()
    if side==1 then
      if not e.lockBase:PlayerHoldsKey(e.Properties.Lock.guidItemClassId) then return false,'door locked' end
    elseif side~=0 then return false,'native lock side unavailable' end
  elseif e.bLocked~=false and e.bLocked~=0 then return false,'door lock state unavailable' end
  return true
end
local function begin(st)
  local e=st.door
  if sameDoor(st)~=true or not sameActor(st) or st.retiring then return false end
  local allowed,why=eligibleDoorH41(e,st.actor)
  if not allowed then st.failure=why return false end
  local component=e.animDoor
  local front=e:IsAccessedFromFront()
  local open=component:GetObjectAnimName(st.userId,false,true,front)
  local close=component:GetObjectAnimName(st.userId,true,false,front)
  if type(open)~='string' or type(close)~='string' or open=='' or close=='' or open==close or #open>128 or #close>128 then
    st.failure='distinct forward native object clips unavailable' return false
  end
  st.openClip,st.closeClip=open,close
  -- The original native Grip may already have started Henry's door clip.
  -- Join that exact observed episode instead of rejecting inUse or invoking
  -- OnUsed again (which would reverse it and repeat manipulation/quest work).
  local join=not st.consoleH41 and e.inUse==1 and e.lastUsedBy==st.userId and
    type(e.curAnim)=='string' and e.curAnim~='' and e.lastAnim==e.curAnim and
    e.bNeedUpdate==1 and e:IsAnimationRunning(0,0)
  local joinAnim,joinDirection=e.curAnim,e.nDirection
  st.direction=join and joinDirection or -e.nDirection st.closeDrive=st.direction==-1
  if not installScopeH40(st) then st.failure='native update/component scope unavailable' return false end
  st.entered=true -- original clip resources may now be controlled by this Grip
  if join then
    local scope=st.scope
    scope.joinedNativeH42=true scope.playToken={} scope.playAnim=joinAnim scope.playDirection=joinDirection
    st.joinedNativeH42=true -- observed original episode, NOT a fabricated Play return
  else
    st.scope.playPermit='USE' st.scope.useActive=true
    local ok,err=pcall(nativeUsed,e,st.actor,0)
    st.scope.playPermit=nil st.scope.useActive=false
    if not ok then failed(st,'native OnUsed: '..tostring(err),true) return true end
    if not st.scope.playToken then
      -- Original OnUsed declined without issuing a clip. No native animation
      -- was acquired; do not strand a pending hand reservation on that outcome.
      st.failure='native use declined' done(st) return true
    end
  end
  if not originalCurrent(st) or not (st.scope.playReturned or st.scope.joinedNativeH42) or e.curAnim~=st.scope.playAnim or
     e.lastAnim~=e.curAnim or e.inUse~=1 or e.bNeedUpdate~=1 then
    failed(st,'native object start not observed',true) return true
  end
  if e.bLocked~=false and e.bLocked~=0 then
    failed(st,'native use did not clear lock',true) return true
  end
  st.driveAnim=e.curAnim st.driveDirection=e.nDirection
  st.playCommandReturned=not join
  if st.consoleH41 then
    -- The old Test paused without a registered hand. This exact original
    -- episode NEVER installs speed zero and is already handed back here.
    st.releasePrepared=true st.releaseDirection=st.driveDirection st.releaseAnim=st.driveAnim
    e:SetAnimationSpeed(0,0,1)
    if not rateReadback(e,1) then failed(st,'test positive rate not observed') return true end
    local wanted=math.min(.9995,st.closeDrive and 1-st.opennessH41 or st.opennessH41)
    e:SetAnimationTime(0,0,wanted)
    if not timeReadback(e,wanted) then failed(st,'test preview readback unavailable; original clip continues') return true end
    st.releaseCommandReturned=true st.stage='NATIVE_FINISH'
    return true
  end
  local paused=pcall(function()
    e:SetAnimationSpeed(0,0,0)
    if not rateReadback(e,0) then error('pause rate readback mismatch') end
    local t=e:GetAnimationTime(0,0)
    if not finite(t) or t<0 or t>1 then error('pause time unavailable') end
    st.lastClipTime=t
  end)
  if not paused then failed(st,'pause not confirmed') return true end
  -- Join the selected clip's paused angle to the requested palm radial around
  -- its current native hinge. Missing geometry resumes the original operation
  -- through its existing release path.
  local sideName=st.driveAnim:match('door_l') and 'left' or 'right'
  local rootOk,root=pcall(function() return e:GetBonePos('Asset_Door-'..sideName) end)
  local pivotOk,pivot=pcall(function() return e:GetBonePos('door_'..sideName..'_pivot') end)
  if not rootOk or not vector(root) or not pivotOk or not vector(pivot) then
    st.releasePrepared=true st.releaseDirection=st.driveDirection st.releaseAnim=st.driveAnim
    failed(st,'named hinge bones unavailable; handing back native operation') return true
  end
  local join,why=D.ClipAngleH40.Join(st.driveAnim,st.lastClipTime,root,pivot,st.command.p)
  if not join then
    st.releasePrepared=true st.releaseDirection=st.driveDirection st.releaseAnim=st.driveAnim
    failed(st,'clip join unavailable: '..tostring(why)) return true
  end
  st.clipJoin=join
  resetMotionH44(st,st.lastClipTime,st.feedAt)
  st.stage='HELD'
  return true
end
local function releaseInUpdate(st)
  local e=st.door
  if not st.entered then done(st) return end
  if st.uncertain or not originalCurrent(st) then return end
  if st.releaseCommandReturned then return end
  if not st.releasePrepared then
    if not (st.playCommandReturned or st.joinedNativeH42) or e.curAnim~=st.driveAnim or e.nDirection~=st.driveDirection or e.lastUsedBy~=st.userId then
      failed(st,'original drive clip replaced',true) return
    end
    -- Releasing a CLOSE must not start a new OPEN merely because the leaf is
    -- still over half open. Hand back this exact original operation, with no
    -- opposite Play, repeated manipulation/crime work, or synthetic endpoint.
    st.releaseDirection=st.driveDirection
    st.releaseAnim=st.driveAnim
    st.releasePrepared=true
  end
  if not originalCurrent(st) or e.curAnim~=st.releaseAnim or e.nDirection~=st.releaseDirection then
    failed(st,'prepared release replaced',true) return
  end
  e:SetAnimationSpeed(0,0,1)
  if not rateReadback(e,1) then failed(st,'resume positive rate not observed') return end
  -- Native DoPlay already enabled updates. No synthetic terminal fields/event.
  st.releaseCommandReturned=true st.stage='NATIVE_FINISH'
end
local function restInUpdateH43(st)
  local e=st.door
  -- Detachment is acknowledged only after the same original clip's actual
  -- paused phase/rate have been read. An uncertain write remains hand-owned.
  if not st.entered or st.uncertain or not originalCurrent(st) or
     e.curAnim~=st.driveAnim or e.nDirection~=st.driveDirection then return false end
  local actual=e:GetAnimationTime(0,0)
  if not finite(actual) or math.abs(actual-st.lastClipTime)>0.0001 or not rateReadback(e,0) or
     not originalCurrent(st) or e.curAnim~=st.driveAnim or e.nDirection~=st.driveDirection then
    failed(st,'partial rest original pause not observed',true) return false
  end
  -- A held endpoint uses the existing real native finish. Capacity exhaustion
  -- does the same; it never evicts another operation or reserves a free hand.
  if actual>=0.9995 or st.joinedNativeH42 then st.retiring=true return false end
  local slot
  for i=1,2 do if not D.restsH43[i] then slot=i break end end
  if not slot then st.retiring=true return false end
  D.restsH43[slot]=st
  st.restSlotH43=slot st.restRequestedH43=nil st.stage='RELEASED_PARTIAL_REST'
  if D.hands[st.side]==st then D.hands[st.side]=nil end
  return true
end
local function postupdate(st)
  if not ownedEpisodeH41(st) then return end
  if sameDoor(st)==false then done(st) return end
  if st.releasePrepared and not st.uncertain and originalCurrent(st) and
     st.door.curAnim=='' and st.door.inUse==0 and st.door.bNeedUpdate==0 and
     st.door.nDirection==st.releaseDirection and st.door.lastAnim==st.releaseAnim and reportReturnedH40(st) then done(st) end
end
local function preupdate(st)
  if not ownedEpisodeH41(st) then return end
  local same=sameDoor(st)
  if same==false then done(st) return end
  if same~=true then failed(st,'door lookup unknown') return end
  if st.consoleH41 then
    if st.stage=='PENDING' then
      if st.retiring then
        if not st.entered then done(st) end -- entered uncertainty is never forgiven
      elseif not begin(st) then done(st) end
    end
    -- No hand motion, feed watchdog, new opposite clip or actor mutation.
    -- Its positive-rate original update remains the completion owner.
    return
  end
  local now=nowMs()
  local feedAt=st.restSlotH43 and D.restFeedAtH43 or st.feedAt
  if not now or not feedAt or now-feedAt>80 or not sameActor(st) then st.retiring=true end
  -- A new native lock or unknown lock state revokes controller seeking too.
  -- Retire through the exact existing operation; never unlock, seek an
  -- endpoint, or start another animation to clean up our paused clip.
  local allowed,why=eligibleDoorH41(st.door,st.actor,st.stage=='PENDING')
  if not allowed then st.failure=why st.retiring=true end
  if st.stage=='PENDING' then
    if st.retiring then
      if st.entered then releaseInUpdate(st) else done(st) end
      return
    end
    if not begin(st) then done(st) end
    return
  end
  if st.retiring then releaseInUpdate(st) return end
  if st.restRequestedH43 then
    if restInUpdateH43(st) then return end
    if st.retiring then releaseInUpdate(st) end
    return
  end
  if st.restSlotH43 then
    if not originalCurrent(st) or st.door.curAnim~=st.driveAnim or st.door.nDirection~=st.driveDirection or
       not rateReadback(st.door,0) or not timeReadback(st.door,st.lastClipTime) then
      failed(st,'rested original clip replaced',true)
    end
    return
  end
  if not originalCurrent(st) or st.door.curAnim~=st.driveAnim or st.door.nDirection~=st.driveDirection then
    failed(st,'held original owner replaced',true) return
  end
  local e=st.door
  local actual=e:GetAnimationTime(0,0)
  if not finite(actual) or math.abs(actual-st.lastClipTime)>0.0001 or not rateReadback(e,0) then
    failed(st,'held clip has another writer',true) return
  end
  -- Invert the same selected clip's curve at the fixed join angle plus signed
  -- palm displacement. Native clip time is not proportional to leaf angle.
  local sideName=st.driveAnim:match('door_l') and 'left' or 'right'
  local rootOk,root=pcall(function() return e:GetBonePos('Asset_Door-'..sideName) end)
  local pivotOk,pivot=pcall(function() return e:GetBonePos('door_'..sideName..'_pivot') end)
  if not rootOk or not vector(root) or not pivotOk or not vector(pivot) then
    st.releasePrepared=true st.releaseDirection=st.driveDirection st.releaseAnim=st.driveAnim
    failed(st,'hinge bones lost during held drive') return
  end
  local p,err=D.ClipAngleH40.Map(st.clipJoin,st.lastClipTime,root,pivot,st.command.p)
  if not p then
    st.releasePrepared=true st.releaseDirection=st.driveDirection st.releaseAnim=st.driveAnim
    failed(st,'clip map unavailable: '..tostring(err)) return
  end
  local wanted=math.max(0,math.min(0.9995,p))
  e:SetAnimationTime(0,0,wanted)
  if not timeReadback(e,wanted) or not rateReadback(e,0) or not originalCurrent(st) then
    failed(st,'controller time write not observed') return
  end
  st.lastClipTime=e:GetAnimationTime(0,0)
  sampleMotionH44(st,st.lastClipTime)
end
local function requestRelease(side)
  local st=D.hands[side]
  if st then
    st.retiring=true
    if not st.entered then done(st) end -- only a scheduler wake was issued
  end
end
local function releaseRestsH43()
  for i=1,2 do local st=D.restsH43[i] if st then st.retiring=true end end
end
local function restCountH43()
  local n=0 for i=1,2 do if D.restsH43[i] then n=n+1 end end return n
end
local timerArmed=false
local function watch()
  timerArmed=false
  local now=nowMs()
  for side=0,1 do
    local st=D.hands[side]
    if st then
      if not now or now-st.feedAt>80 then requestRelease(side) end
      st=D.hands[side]
      if st then pcall(st.door.Activate,st.door,1) end -- wake only, never mutate a clip here
    end
  end
  for i=1,2 do
    local st=D.restsH43[i]
    if st then
      if not now or not D.restFeedAtH43 or now-D.restFeedAtH43>80 then st.retiring=true end
      pcall(st.door.Activate,st.door,1)
    end
  end
  if D.hands[0] or D.hands[1] or restCountH43()>0 then timerArmed=true Script.SetTimer(25,watch) end
end
local function armWatch()
  if not timerArmed then timerArmed=true Script.SetTimer(25,watch) end
end
local function reserve(side,actor,id,p,grip,now,claim,offered)
  local e
  if offered and offered~=0 then
    -- A native offered target is an identity, not a hint to choose another
    -- nearby door. Still require current native entity, class and near bounds.
    e=System and System.GetEntity and System.GetEntity(offered)
    if type(e)~='table' or e.class~='AnimDoor' or type(e.GetWorldBBox)~='function' then return end
    local a,b=e:GetWorldBBox()
    local near=vector(a) and vector(b) and distance(p,a,b)<=0.35
    if not near and retainedCandidateH44 then
      local retained,d=retainedCandidateH44(p)
      near=retained==e and finite(d) and d<=0.35
    end
    if not near then return end
  else
    e=nearest(p) -- off-gaze acquisition with no native offered target
  end
  if not e or D.testsH41[e] then return end
  local other=D.hands[1-side]
  if other and other.door==e then return end
  local raw=e:GetRawId()
  if not integer(raw,1,4294967295) or System.GetEntity(raw)~=e then return end
  local okUse,allowed,why=pcall(eligibleDoorH41,e,actor)
  if not okUse or not allowed then sayWhy({failure=okUse and why or 'door check failed'}) return end
  for i=1,2 do
    local rested=D.restsH43[i]
    if rested and rested.door==e then
      -- Same native operation, a fresh current hand claim. Rebase the palm at
      -- its actual phase instead of calling OnUsed/DoPlay or replaying costs.
      if rested.retiring or rested.uncertain or not sameActor(rested) or rested.actor~=actor or
         not originalCurrent(rested) or e.curAnim~=rested.driveAnim or e.nDirection~=rested.driveDirection then return end
      local actual=e:GetAnimationTime(0,0)
      if not finite(actual) or not timeReadback(e,rested.lastClipTime) or not rateReadback(e,0) then return end
      local sideName=rested.driveAnim:match('door_l') and 'left' or 'right'
      local join=D.ClipAngleH40.Join(rested.driveAnim,actual,e:GetBonePos('Asset_Door-'..sideName),e:GetBonePos('door_'..sideName..'_pivot'),p)
      if not join or not timeReadback(e,actual) or not rateReadback(e,0) or not originalCurrent(rested) or
         e.curAnim~=rested.driveAnim or e.nDirection~=rested.driveDirection then return end
      D.hands[side]=rested
      D.restsH43[i]=nil rested.restSlotH43=nil
      rested.side=side rested.claim=claim rested.feedAt=now rested.command={p=p,g=grip}
      rested.clipJoin=join rested.lastClipTime=actual rested.stage='HELD'
      resetMotionH44(rested,actual,now)
      armWatch() return
    end
  end
  -- CL-D: ask the door's own lock/use rules BEFORE taking the hand. a door we may not open is never reserved, so this
  -- same Grip goes straight back to the game (locked -> the game's lockpick/key prompt) and one line says why.
  local st={side=side,door=e,doorId=raw,actor=actor,userId=actor.id,playerId=id,
    stage='PENDING',feedAt=now,command={p=p,g=grip},retiring=false,claim=claim}
  D.hands[side]=st -- publish the owner before original OnUsed can reenter
  -- This callback already runs through the verified original-first native
  -- script Context. Grip starts native OnUsed here, before an A/player clip.
  -- Waiting for this idle entity's first OnUpdate made A the effective start.
  -- The existing one-use DoPlay permit selects object-only; no actor flags.
  st.inUpdate=true
  local started,err=pcall(begin,st)
  st.inUpdate=false
  if not started then failed(st,'Grip native start: '..tostring(err),st.entered)
  elseif not err then done(st) return end
  if D.hands[side]~=st then return end
  -- Original DoPlayAnimation already activated this door's native updates.
  armWatch()
end
local function parse(input)
  if type(input)~='string' or #input>512 then return nil end
  local f={} for x in (input..'|'):gmatch('([^|]*)|') do f[#f+1]=x end
  if #f~=16 and #f~=18 then return nil end
  local p={serial=tonumber(f[1]),action=f[2],player=tonumber(f[3]),body=tonumber(f[4]),request=tonumber(f[5]),tick=tonumber(f[6]),hand={}}
  if not integer(p.serial,1,9007199254740991) or not integer(p.player,1,4294967295) or
     not integer(p.body,1,9007199254740991) or not integer(p.request,1,9007199254740991) or
     not integer(p.tick,1,9007199254740991) or
     (p.action~='feed' and p.action~='release' and p.action~='releaseall' and p.action~='clear' and p.action~='probe') then return nil end
  for side=0,1 do
    local base=7+side*4 local g,x,y,z=tonumber(f[base]),tonumber(f[base+1]),tonumber(f[base+2]),tonumber(f[base+3])
    if not finite(g) or g < -1 or g>1 or not finite(x) or not finite(y) or not finite(z) then return nil end
    local claim=tonumber(f[15+side])
    if not integer(claim,0,9007199254740991) or (p.action=='feed' and g>=0.25 and claim==0) then return nil end
    local offered=#f==18 and tonumber(f[17+side]) or 0
    if not integer(offered,0,4294967295) then return nil end
    p.hand[side]={g=g,p={x=x,y=y,z=z},claim=claim,offered=offered}
  end
  if (p.action=='clear' or p.action=='releaseall' or p.action=='probe') and (p.hand[0].g~=-1 or p.hand[1].g~=-1) then return nil end
  return p
end
local function sameIdentity(p)
  return D.ident and D.ident.player==p.player and D.ident.body==p.body and D.ident.request==p.request
end
local function identReply(p)
  local id=D.ident or p
  return string.format('IDENT|%.0f|%.0f|%.0f|%.0f',p.serial,id.player,id.body,id.request)
end
local function reply(p,emptyProbe)
  local m,r,d0,d1=0,0,0,0
  for side=0,1 do
    local st=not emptyProbe and D.hands[side]
    if st then
      local bit=side==0 and 1 or 2 m=m+bit
      if st.retiring then r=r+bit end
      if side==0 then d0=st.doorId else d1=st.doorId end
    end
  end
  -- H40R1 acknowledges HAND release separately from still-owned native rest
  -- debt. A free hand is not a fabricated native endpoint/quest report.
  return string.format('H40R1|%.0f|%.0f|%.0f|%.0f|%d|%d|%.0f|%.0f|%.0f|%d',p.serial,p.player,p.body,p.request,m,r,m==0 and p.serial or D.ackSeq,d0,d1,emptyProbe and 0 or restCountH43())
end
function kcd2vr_door_hand_h40_t2(input)
  local p=parse(input)
  if not p then return 'BAD|0' end
  if not D.installed then return 'BAD|'..p.serial end
  if p.action=='probe' then
    if D.hands[0] or D.hands[1] or restCountH43()>0 then return identReply(p) end
    return reply(p,true)
  end
  if D.lastSerial and (p.serial<D.lastSerial or (p.serial==D.lastSerial and input~=D.lastInput)) then return 'BAD|'..p.serial end
  if not sameIdentity(p) then
    if D.hands[0] or D.hands[1] or restCountH43()>0 then requestRelease(0) requestRelease(1) releaseRestsH43() return identReply(p) end
    D.ident={player=p.player,body=p.body,request=p.request}
    D.lastSerial=nil D.lastInput=nil D.seenClaims={[0]=0,[1]=0}
  end
  -- A duplicate transport attempt never repeats start, seek, sound, crime or
  -- wake. Native OnUpdate may still advance its own retained completion.
  if p.serial==D.lastSerial then return reply(p) end
  if p.action=='feed' and not currentPlayer(p.player) then return 'BAD|'..p.serial end
  local now=nowMs()
  if not now then return 'BAD|'..p.serial end
  D.lastSerial=p.serial D.lastInput=input
  if p.action~='feed' then
    requestRelease(0) requestRelease(1) releaseRestsH43()
    if not D.hands[0] and not D.hands[1] and restCountH43()==0 then D.ackSeq=p.serial else D.cleanupSerial=p.serial end
    return reply(p)
  end
  D.restFeedAtH43=now
  local actor=currentPlayer(p.player)
  for side=0,1 do
    local h=p.hand[side] local st=D.hands[side]
    if h.g>=0 and h.g<0.30 and st and h.claim==st.claim and st.stage=='HELD' and not st.retiring then
      -- Grip release during ordinary movement must not always strand a paused
      -- leaf. Continue this same native operation; no new Use/Play/start/event.
      -- Its native direction is retained even after a reverse hand excursion:
      -- opposite DoPlay would repeat manipulation/volume semantics.
      st.releaseMovingH44=movingReleaseH44(st,now)
      st.releaseRateH44=st.motionRateH44
      st.feedAt=now
      if st.releaseMovingH44 then st.retiring=true
      else st.restRequestedH43=true end
    elseif h.g<0.25 then requestRelease(side)
    elseif st then
      if h.claim~=st.claim then requestRelease(side)
      else st.feedAt=now if not st.retiring then st.command=h st.restRequestedH43=nil end end
    elseif h.g>0.55 and h.claim~=D.seenClaims[side] then
      D.seenClaims[side]=h.claim -- an original C++ claim can acquire at most once
      reserve(side,actor,p.player,h.p,h.g,now,h.claim,h.offered)
    end
  end
  return reply(p)
end
