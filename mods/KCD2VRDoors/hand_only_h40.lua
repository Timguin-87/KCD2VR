       st.claim==p.hand[side].claim and st.command and st.command.g>=.30 and now-st.feedAt<=80 and
       st.stage=='HELD' and originalCurrent(st) and st.door.curAnim==st.driveAnim and st.door:IsAnimationRunning(0,0) then
      local ok,t,rate,point=pcall(function()
        local e=st.door;local actual=e:GetAnimationTime(0,0)
