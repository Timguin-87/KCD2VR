function D.Install()
  if D.installed then return true end
  local A=rawget(_G,'AnimDoor')
  if type(A)~='table' or type(A.Server)~='table' or type(A.OnUsed)~='function' or type(A.Server.OnUpdate)~='function' or
     not Script or type(Script.SetTimer)~='function' then return false end
  nativeUsed=A.OnUsed
  local update=A.Server.OnUpdate
  A.Server.OnUpdate=function(self,dt)
    local st
    for side=0,1 do if D.hands[side] and D.hands[side].door==self then st=D.hands[side] break end end
    if not st then for i=1,2 do if D.restsH43[i] and D.restsH43[i].door==self then st=D.restsH43[i] break end end end
    st=st or D.testsH41[self]
    if st and st.inUpdate then return update(self,dt) end
    if st then
      st.inUpdate=true
      local ok,err=pcall(preupdate,st)
      if not ok then failed(st,'door update: '..tostring(err),st.switchAttempted and not st.switchReturned) end
    end
    -- The selected door's own composed callback is the only terminal observer.
    -- No packet/timer setter can fabricate this token, and each play consumes
    -- its permit and installs a new generation before its original call.
    local scope=st and ownedEpisodeH41(st) and st.scope
    local prior=scope and scope.updateToken
    if scope then scope.updateToken=scope.playToken end
    local result=packScopeH40(pcall(update,self,dt))
    if scope then scope.updateToken=prior end
    if st then st.inUpdate=false end
    if not result[1] then error(result[2],0) end
    if st then postupdate(st) end
    if D.cleanupSerial and not D.hands[0] and not D.hands[1] and restCountH43()==0 then D.ackSeq=D.cleanupSerial D.cleanupSerial=nil end
    return unpackScopeH40(result,2)
  end
  D.installed=true return true
end
